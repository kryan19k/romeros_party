export const dicts: Record<Lang, Dict> = { en, es };

export function fmt(s: string, vars: Record<string, string | number>) {
  return s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ""));
}

export function pickLang(cookieLang: string | undefined, acceptLanguage: string | null): Lang {
  if (cookieLang === "en" || cookieLang === "es") return cookieLang;
  return acceptLanguage?.toLowerCase().startsWith("es") ? "es" : "en";
}
